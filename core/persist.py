"""状态持久化：Portfolio ⇄ JSON（Windows 原子写）。重启不丢，可手动 patch。

落盘内容：每标的 H、各档 armed、已投放储备、累计注资、成本基础、pending 分批、
冻结状态、触发记录；现金流账；以及实盘交易日序号（day_index/last_run_date）。
"""
from __future__ import annotations

import json
import os
import shutil
from collections import deque
from datetime import datetime
from pathlib import Path

from core.helpers import atomic_write_text, resolve
from core.state import CashFlow, Portfolio, SymbolState

AUDIT_PATH = "data/audit.jsonl"
ADVICE_SNAPSHOT_PATH = "data/advice_snapshots.jsonl"


def _advice_snapshot_meta_path(path: str | Path) -> Path:
    """Return the sidecar path for append-only advice snapshot health metadata."""
    return resolve(path).with_suffix(".meta.json")


def _read_advice_snapshot_meta(path: str | Path) -> dict:
    meta_path = _advice_snapshot_meta_path(path)
    if not meta_path.exists():
        return {}
    try:
        payload = json.loads(meta_path.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, json.JSONDecodeError):
        return {}
    return payload if isinstance(payload, dict) else {}


def save_portfolio(pf: Portfolio, path: str | Path) -> None:
    data = {
        "symbols": {t: s.to_dict() for t, s in pf.symbols.items()},
        "flows": [vars(f) for f in pf.flows],
        "day_index": pf.day_index,
        "last_run_date": pf.last_run_date,
        "safe_ticker": pf.safe_ticker,
        "safe_shares": pf.safe_shares,
        "target_safe_weight": pf.target_safe_weight,
    }
    atomic_write_text(resolve(path), json.dumps(data, ensure_ascii=False, indent=2))


def load_portfolio(path: str | Path) -> Portfolio | None:
    p = resolve(path)
    if not p.exists():
        return None
    with open(p, "r", encoding="utf-8") as f:
        data = json.load(f)
    symbols = {t: SymbolState.from_dict(d) for t, d in data.get("symbols", {}).items()}
    flows = [CashFlow(**fl) for fl in data.get("flows", [])]
    return Portfolio(symbols=symbols, flows=flows,
                     day_index=int(data.get("day_index", 0)),
                     last_run_date=str(data.get("last_run_date", "")),
                     safe_ticker=str(data.get("safe_ticker", "SGOV")),
                     safe_shares=float(data.get("safe_shares", 0.0)),
                     target_safe_weight=float(data.get("target_safe_weight", 0.0)))


def backup_state(path: str | Path) -> Path | None:
    """改动前把 state 备份到 .bak，patch 失误可恢复。"""
    p = resolve(path)
    if not p.exists():
        return None
    bak = p.with_suffix(p.suffix + ".bak")
    shutil.copy2(p, bak)
    return bak


def audit_log(action: str, detail: dict, note: str = "",
              path: str | Path = AUDIT_PATH) -> None:
    """所有人工改动留痕（who 恒为用户 / when / what / why），追加 JSONL。"""
    rec = {"ts": datetime.now().isoformat(timespec="seconds"),
           "action": action, "detail": detail, "note": note}
    p = resolve(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "a", encoding="utf-8") as f:
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")


def advice_snapshot_log(detail: dict, path: str | Path = ADVICE_SNAPSHOT_PATH) -> dict:
    """Append one generated /api/state advice snapshot.

    This is separate from audit_log on purpose: audit_log is for user-confirmed
    state mutations, while advice snapshots are read-only evidence generated by
    opening or refreshing the dashboard.
    """
    rec = {"ts": datetime.now().isoformat(timespec="seconds"), **detail}
    p = resolve(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    existed_before = p.exists()
    line = json.dumps(rec, ensure_ascii=False, separators=(",", ":")) + "\n"
    with open(p, "a", encoding="utf-8", newline="") as f:
        f.write(line)
        f.flush()
        os.fsync(f.fileno())

    previous = _read_advice_snapshot_meta(p)
    previous_count = previous.get("row_count")
    row_count = (
        int(previous_count) + 1
        if isinstance(previous_count, int)
        else (1 if not existed_before else None)
    )
    previous_valid_count = previous.get("valid_row_count")
    previous_invalid_count = previous.get("invalid_row_count")
    valid_row_count = (
        int(previous_valid_count) + 1
        if isinstance(previous_valid_count, int)
        else (1 if not existed_before else None)
    )
    invalid_row_count = (
        int(previous_invalid_count)
        if isinstance(previous_invalid_count, int) else (0 if not existed_before else None)
    )
    meta = {
        "schema_version": 1,
        "journal_path": p.as_posix(),
        "row_count": row_count,
        "row_count_known": row_count is not None,
        "valid_row_count": valid_row_count,
        "invalid_row_count": invalid_row_count,
        "first_ts": previous.get("first_ts") or rec.get("ts"),
        "last_ts": rec.get("ts"),
        "last_snapshot_id": rec.get("snapshot_id"),
        "last_write_durable": True,
        "updated_at": datetime.now().isoformat(timespec="seconds"),
    }
    atomic_write_text(
        _advice_snapshot_meta_path(p),
        json.dumps(meta, ensure_ascii=False, indent=2) + "\n",
    )
    return rec


def _read_jsonl_tail(path: Path, limit: int) -> list[bytes]:
    """Read only the last *limit* physical lines of a potentially large JSONL."""
    if limit <= 0:
        return []
    with open(path, "rb") as f:
        position = f.seek(0, os.SEEK_END)
        buffer = b""
        chunk_size = 1024 * 1024
        while position > 0 and buffer.count(b"\n") <= limit:
            size = min(chunk_size, position)
            position -= size
            f.seek(position)
            buffer = f.read(size) + buffer
    return buffer.splitlines()[-limit:]


def iter_advice_snapshots(path: str | Path = ADVICE_SNAPSHOT_PATH):
    """Stream every advice snapshot in file order.

    The normal API reader intentionally reads only the tail because the journal
    is large.  Historical research such as the golden-pit review must use this
    iterator instead; otherwise a high-frequency dashboard can hide older
    trading sessions behind the last few hundred physical rows.
    """
    p = resolve(path)
    if not p.exists():
        return
    with open(p, "rb") as f:
        for raw_bytes in f:
            raw = raw_bytes.decode("utf-8", errors="replace").strip()
            if not raw:
                continue
            try:
                row = json.loads(raw)
            except json.JSONDecodeError:
                yield {"error": "invalid_jsonl_row", "raw": raw[:500]}
                continue
            if isinstance(row, dict):
                yield row
            else:
                yield {"error": "invalid_snapshot_row", "raw": raw[:500]}


def scan_advice_snapshot_journal(path: str | Path = ADVICE_SNAPSHOT_PATH) -> dict:
    """Read the full journal and return independently computed health fields."""
    p = resolve(path)
    total = 0
    invalid = 0
    first_ts = None
    last_ts = None
    last_snapshot_id = None
    for row in iter_advice_snapshots(p):
        total += 1
        if row.get("error"):
            invalid += 1
            continue
        ts = str(row.get("ts") or "")
        if first_ts is None and ts:
            first_ts = ts
        if ts:
            last_ts = ts
        if row.get("snapshot_id"):
            last_snapshot_id = row.get("snapshot_id")
    return {
        "journal_path": p.as_posix(),
        "row_count": total,
        "row_count_known": True,
        "valid_row_count": total - invalid,
        "invalid_row_count": invalid,
        "first_ts": first_ts,
        "last_ts": last_ts,
        "last_snapshot_id": last_snapshot_id,
    }


def rebuild_advice_snapshot_meta(path: str | Path = ADVICE_SNAPSHOT_PATH) -> dict:
    """Recount an existing journal and repair its restart-health sidecar.

    This is an explicit maintenance operation because recounting a large
    journal on every dashboard request would be wasteful.  It never changes
    the journal rows, portfolio state, configuration, or today's advice.
    """
    p = resolve(path)
    previous = _read_advice_snapshot_meta(p)
    meta = {
        "schema_version": 1,
        **scan_advice_snapshot_journal(p),
        "last_write_durable": bool(previous.get("last_write_durable", False)),
        "updated_at": datetime.now().isoformat(timespec="seconds"),
    }
    atomic_write_text(
        _advice_snapshot_meta_path(p),
        json.dumps(meta, ensure_ascii=False, indent=2) + "\n",
    )
    return meta


def load_advice_snapshots(limit: int = 50,
                          path: str | Path = ADVICE_SNAPSHOT_PATH) -> list[dict]:
    """Read the latest advice snapshots without scanning old rows twice."""
    n = max(0, min(int(limit or 0), 500))
    if n <= 0:
        return []
    p = resolve(path)
    if not p.exists():
        return []
    rows: deque[dict] = deque(maxlen=n)
    for raw_bytes in _read_jsonl_tail(p, n):
        raw = raw_bytes.decode("utf-8", errors="replace").strip()
        if not raw:
            continue
        try:
            rows.append(json.loads(raw))
        except json.JSONDecodeError:
            rows.append({"error": "invalid_jsonl_row", "raw": raw[:500]})
    return list(rows)


def advice_snapshot_storage(path: str | Path = ADVICE_SNAPSHOT_PATH) -> dict:
    """Return restart-safe diagnostics for the append-only advice journal."""
    p = resolve(path)
    meta_path = _advice_snapshot_meta_path(p)
    meta = _read_advice_snapshot_meta(p)
    latest = load_advice_snapshots(limit=1, path=p)
    latest_row = latest[-1] if latest else {}
    try:
        stat = p.stat()
        bytes_on_disk = int(stat.st_size)
        modified_at = datetime.fromtimestamp(stat.st_mtime).isoformat(timespec="seconds")
    except OSError:
        bytes_on_disk = 0
        modified_at = ""
    return {
        "persistent": p.exists() and p.is_file(),
        "absolute_path": p.as_posix(),
        "metadata_path": meta_path.as_posix(),
        "metadata_present": meta_path.exists(),
        "bytes_on_disk": bytes_on_disk,
        "modified_at": modified_at,
        "row_count": meta.get("row_count"),
        "row_count_known": bool(meta.get("row_count_known", False)),
        "valid_row_count": meta.get("valid_row_count"),
        "invalid_row_count": meta.get("invalid_row_count"),
        "first_ts": meta.get("first_ts"),
        "last_snapshot_id": meta.get("last_snapshot_id") or latest_row.get("snapshot_id"),
        "last_ts": meta.get("last_ts") or latest_row.get("ts"),
        "durability": "append_flush_fsync",
    }
