def _resolve(value: str | Path) -> Path:
    path = Path(value)
    return path if path.is_absolute() else ROOT / path


def _atomic_csv(frame: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    try:
        frame.to_csv(temporary, index=False, encoding="utf-8-sig", lineterminator="\n")
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def _read_verified_csv(path: Path, required: set[str]) -> tuple[pd.DataFrame, dict]:
    if not path.exists():
        raise ValueError(f"overlay evidence input is missing: {path}")
    sidecar = manifest_path(path)
    if not sidecar.exists():
        raise ValueError(f"overlay evidence input manifest is missing: {sidecar}")
    try:
        manifest = json.loads(sidecar.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError, json.JSONDecodeError) as exc:
        raise ValueError(f"overlay evidence input manifest is invalid: {sidecar}") from exc
    digest = file_sha256(path)
    if manifest.get("content_sha256") != digest:
        raise ValueError(f"overlay evidence input hash mismatch: {path}")
    frame = pd.read_csv(path, dtype=str, keep_default_na=False)
    missing = required - set(frame.columns)
    if missing:
        raise ValueError(f"overlay evidence input missing columns: {sorted(missing)}")
    return frame, manifest


def _read_registry(path: Path) -> dict:
    try:
        payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except (OSError, ValueError, TypeError, yaml.YAMLError) as exc:
        raise ValueError(f"invalid incumbent overlay decision registry: {path}") from exc
    if int(payload.get("schema_version") or 0) != 1:
        raise ValueError("incumbent overlay decision registry schema_version must be 1")
    if str(payload.get("taxonomy_id") or "") != "us_growth_risk_chain_taxonomy_v2":
        raise ValueError("incumbent overlay decision registry taxonomy_id mismatch")
    decisions = payload.get("decisions")
    if not isinstance(decisions, list) or not decisions:
        raise ValueError("incumbent overlay decision registry has no decisions")
    return payload


def _date(value: object, *, field: str) -> str:
    raw = str(value or "").strip()[:10]
    try:
        return date.fromisoformat(raw).isoformat()
    except ValueError as exc:
        raise ValueError(f"invalid {field}: {value!r}") from exc


def _bool(value: object) -> bool:
    return str(value).strip().lower() in {"true", "1", "yes"}


def _evidence_id(row: pd.Series) -> str:
    return f"sec_overlay:{row.get('overlay_id', '')}:{row.get('accession_number', '')}"


def _resolved_effective_from(decision: dict, template_row: pd.Series) -> str:
    value = str(decision.get("effective_from") or "").strip()
    if not value or value == "evidence_available_date":
        value = str(template_row.get("evidence_available_date") or "").strip()
    return _date(value, field="effective_from")


def _validate_and_apply(
    template: pd.DataFrame,
    documents: pd.DataFrame,
    registry: dict,
    taxonomy: dict,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    reviewed = template.copy()
    for column in REVIEW_TEMPLATE_COLUMNS:
        if column not in reviewed.columns:
            reviewed[column] = ""
    reviewed = reviewed[REVIEW_TEMPLATE_COLUMNS].copy()
    document_by_id = {
        _evidence_id(row): row
        for _, row in documents.iterrows()
    }
    template_by_id = {
        str(row.get("evidence_id") or ""): row
        for _, row in reviewed.iterrows()
    }
    categories = set((taxonomy.get("risk_chains") or {}).keys())
    seen_evidence: set[str] = set()
    accepted_tickers: set[str] = set()
    audit_rows = []

    for position, decision in enumerate(registry["decisions"], start=1):
        if not isinstance(decision, dict):
            raise ValueError(f"overlay decision {position} is not a mapping")
        decision_id = f"decision:{position:03d}"
        evidence_id = str(decision.get("evidence_id") or "").strip()
        ticker = str(decision.get("ticker") or "").strip().upper()
        if not evidence_id or evidence_id in seen_evidence:
            raise ValueError(f"duplicate or empty overlay evidence_id: {decision_id}")
        seen_evidence.add(evidence_id)
        if evidence_id not in document_by_id or evidence_id not in template_by_id:
            raise ValueError(f"overlay decision references absent evidence: {evidence_id}")
        document = document_by_id[evidence_id]
        template_row = template_by_id[evidence_id]
        if ticker != str(document.get("ticker") or "").strip().upper():
            raise ValueError(f"ticker/evidence mismatch for {decision_id}")
        if str(decision.get("security_id") or "").strip() != str(document.get("security_id") or ""):
            raise ValueError(f"security/evidence mismatch for {decision_id}")
        if str(decision.get("issuer_id") or "").strip() != str(document.get("issuer_id") or ""):
            raise ValueError(f"issuer/evidence mismatch for {decision_id}")
        if str(decision.get("expected_accession_number") or "").strip() not in {
            "",
            str(document.get("accession_number") or ""),
        }:
            raise ValueError(f"accession/evidence mismatch for {decision_id}")
        extraction_status = str(document.get("extraction_status") or "")
        if extraction_status not in {
            "business_section_extracted",
            "business_text_fallback_candidate",
        }:
            raise ValueError(f"overlay evidence is not a usable business-text candidate: {evidence_id}")
        raw_match = str(decision.get("expected_raw_sha256") or "").strip() == str(document.get("raw_sha256") or "")
        excerpt_match = str(decision.get("expected_excerpt_sha256") or "").strip() == str(document.get("business_excerpt_sha256") or "")
        if not raw_match or not excerpt_match:
            raise ValueError(
                f"hash-locked incumbent evidence changed for {decision_id}: "
                f"raw_match={raw_match}, excerpt_match={excerpt_match}"
            )
        if not _bool(document.get("raw_manifest_verified")):
            raise ValueError(f"incumbent SEC raw manifest is not verified: {decision_id}")
        risk_chain = str(decision.get("risk_chain") or "").strip().lower()
        confidence = str(decision.get("confidence") or "").strip().lower()
        status = str(decision.get("status") or "").strip().lower()
        if risk_chain not in categories or risk_chain == "unclassified":
            raise ValueError(f"unsupported incumbent risk chain: {risk_chain}")
        if confidence not in {"high", "medium"} or status != "accepted":
            raise ValueError(f"accepted incumbent decision requires high/medium confidence: {decision_id}")
        available = _date(document.get("evidence_available_date"), field="evidence_available_date")
        effective_from = _resolved_effective_from(decision, template_row)
        effective_to = str(decision.get("effective_to") or "").strip()
        if effective_to:
            effective_to = _date(effective_to, field="effective_to")
        if available > effective_from or (effective_to and effective_from > effective_to):
            raise ValueError(f"incumbent future-data/effective interval guard failed: {decision_id}")
        row_index = reviewed.index[reviewed["evidence_id"].eq(evidence_id)]
        if len(row_index) != 1:
            raise ValueError(f"overlay evidence_id is not unique: {evidence_id}")
        index = row_index[0]
        reviewed.at[index, "risk_chain"] = risk_chain
        reviewed.at[index, "effective_from"] = effective_from
        reviewed.at[index, "effective_to"] = effective_to
        reviewed.at[index, "confidence"] = confidence
        reviewed.at[index, "status"] = status
        reviewed.at[index, "notes"] = (
            f"review_registry={registry.get('review_registry_id')}; "
            f"{str(decision.get('notes') or '').strip()}"
        ).strip(" ;")
        accepted_tickers.add(ticker)
        audit_rows.append({
            "decision_id": decision_id,
            "ticker": ticker,
            "evidence_id": evidence_id,
            "security_id": document.get("security_id", ""),
            "issuer_id": document.get("issuer_id", ""),
            "risk_chain": risk_chain,
            "confidence": confidence,
            "status": status,
            "effective_from": effective_from,
            "effective_to": effective_to,
            "evidence_available_date": available,
            "extraction_status": extraction_status,
            "raw_manifest_verified": True,
            "raw_sha256_match": raw_match,
            "excerpt_sha256_match": excerpt_match,
            "decision_status": "applied",
            "decision_note": decision.get("notes", ""),
        })

    expected_tickers = set(documents["ticker"].astype(str).str.upper())
    if accepted_tickers != expected_tickers:
        raise ValueError(
            "incumbent overlay must decide every fetched current stock: "
            f"missing={sorted(expected_tickers - accepted_tickers)}, "
            f"extra={sorted(accepted_tickers - expected_tickers)}"
        )
    return reviewed, pd.DataFrame(audit_rows, columns=DECISION_AUDIT_COLUMNS)


