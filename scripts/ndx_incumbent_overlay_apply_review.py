"""Apply the Codex-authored, hash-locked incumbent SEC overlay decisions.

This is a research-only bridge for the eight configured stock incumbents.  It
does not score securities, read prices/returns, change ``config.yaml`` or
change today's advice.  Every accepted row is tied to the exact SEC filing
bytes and extracted source excerpt generated by ``ndx_incumbent_overlay.py``.
"""
