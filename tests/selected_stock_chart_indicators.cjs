const assert=require('node:assert/strict');
const {candleSvg,movingAverage,quoteLabel}=require('../web/selected_stock_charts.js');
const bars=Array.from({length:150},(_,index)=>({date:new Date(Date.UTC(2026,0,index+1)).toISOString().slice(0,10),open:100+index,high:102+index,low:99+index,close:101+index}));
assert.equal(movingAverage(bars,5)[3],null);
assert.equal(movingAverage(bars,5)[4],103);
assert.equal(movingAverage(bars,120)[119],160.5);
const visible=bars.slice(120,130);
const svg=candleSvg(visible,null,'day',[],{allBars:bars,start:120});
assert.match(svg,/ma-120/);
assert.match(svg,/MA120: 170.50/,'legend is last visible MA, not latest loaded MA');
assert.match(svg,/points="44.5,/, 'MA starts at first visible bar using hidden warmup');
assert.match(svg,/历史收盘 \$250.00/,'latest loaded historical close does not change with pan');
assert.match(svg,/2026-05-30/);
assert.match(svg,/visible-high/);assert.match(svg,/visible-low/);
assert(!svg.includes('NaN'));
const short=candleSvg(bars.slice(0,4),null,'month');
assert.match(short,/不足5根/);assert(!short.includes('class="moving-average'));
assert.match(short,/完整已加载月线收盘计算/);
assert.throws(()=>candleSvg(visible,null,'day',[],{allBars:bars,start:119}),/Invalid/);
const quote={price:213.66,as_of:'2026-10-16T20:15:00-04:00'};
assert.match(quoteLabel({...quote,session:'REGULAR'}),/^盘中价/);
assert.match(quoteLabel({...quote,session:'POST_MARKET'}),/^盘后价/);
assert.match(quoteLabel({...quote,session:'PRE'}),/^盘前价/);
assert.match(quoteLabel(quote),/^报价/);
assert.equal(quoteLabel({...quote,as_of:'unknown'}),'');
assert.match(candleSvg(visible,null,'day',[],{allBars:bars,start:120,quote:{...quote,session:'POST'}}),/盘后价/);
const fills=[{executed_at:visible[0].date+'T15:00:00Z',side:'BUY',quantity:14,price:visible[0].close},{executed_at:visible[1].date+'T15:00:00Z',side:'SELL',quantity:1,price:visible[1].close}];
const marked=candleSvg(visible,null,'day',fills,{allBars:bars,start:120});
assert.match(marked,/>B<\/text>/);assert.match(marked,/>S<\/text>/);
assert.match(marked,/买入 14 股/);assert.match(marked,/卖出 1 股/);
assert.match(marked,/#0987da/);assert.match(marked,/#dc9b13/);
console.log('PASS broker chart: warmup, viewport MA, missing history, period labels, historical reference, BUY/SELL and explicit quote sessions');
